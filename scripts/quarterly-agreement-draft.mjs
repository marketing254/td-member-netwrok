/**
 * Draft of the personalised agreement PDFs and the two team alerts after
 * the quarterly-plan change (Lester, 5 Oct 2026). LOCAL ONLY.
 *
 * Sends ONLY to DRAFT_TO. The team distribution list is replaced in the
 * loaded copy of teamNotify.ts, so nobody on the real list gets anything.
 *
 *   node scripts/quarterly-agreement-draft.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import nodemailer from "nodemailer";

const DRAFT_TO = "rushdhaakbar82@gmail.com";
const DRAFT_CC = ["lester@ekwa.com"];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
for (const line of fs.readFileSync(path.join(root, ".env.local"), "utf8").split(/\r?\n/)) {
  const m = line.match(/^\s*([\w.]+)\s*=\s*(.*)\s*$/);
  if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^"(.*)"$/, "$1");
}
delete process.env.VERCEL; // force the local-Chrome path in the PDF renderer

/** Load a server-only TS module as a temporary sibling copy with imports rewritten. */
async function loadCopy(rel, rewrite) {
  const src = path.join(root, rel);
  let code = fs.readFileSync(src, "utf8").replace(/^import "server-only";\r?\n/m, "");
  code = rewrite(code);
  const tmp = path.join(path.dirname(src), `.draft-${path.basename(src)}`);
  fs.writeFileSync(tmp, code);
  try {
    return await import(pathToFileURL(tmp).href);
  } finally {
    fs.unlinkSync(tmp);
  }
}

// resolveLocalChrome: just drop server-only.
const chromeTmp = path.join(root, "src/lib/pdf/.draft-resolveLocalChrome.ts");
fs.writeFileSync(chromeTmp, fs.readFileSync(path.join(root, "src/lib/pdf/resolveLocalChrome.ts"), "utf8").replace(/^import "server-only";\r?\n/m, ""));

let pdfMod, teamMod;
try {
  pdfMod = await loadCopy("src/lib/pdf/foundingAgreementPdf.ts", (c) =>
    c
      .replace('from "@/lib/billing/partnerPlan"', 'from "../billing/partnerPlan.ts"')
      .replace('import("./resolveLocalChrome")', 'import("./.draft-resolveLocalChrome.ts")'),
  );
  teamMod = await loadCopy("src/lib/email/teamNotify.ts", (c) =>
    c.replace(/export const TEAM_DISTRIBUTION_LIST = \[[\s\S]*?\]\.filter\(Boolean\);/, `export const TEAM_DISTRIBUTION_LIST = ["${DRAFT_TO}"];`),
  );
} catch (err) {
  fs.unlinkSync(chromeTmp);
  throw err;
}

